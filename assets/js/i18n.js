window.LANG = (function () {
  try { return localStorage.getItem("feh_lang") || window.SITE_CONFIG.DEFAULT_LANG; } catch (e) { return window.SITE_CONFIG.DEFAULT_LANG; }
})();

/* t("key") → interface text; tf(obj, "title") → obj.title_ar / obj.title_en */
window.t = function (key) { return (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key; };
window.tf = function (obj, field) {
  if (!obj) return "";
  const other = LANG === "ar" ? "en" : "ar";
  return obj[field + "_" + LANG] || obj[field + "_" + other] || "";
};
window.setLang = function (lang) {
  try { localStorage.setItem("feh_lang", lang); } catch (e) {}
  location.reload();
};
window.applyI18n = function (root) {
  (root || document).querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  (root || document).querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
};
document.documentElement.lang = LANG;
document.documentElement.dir = LANG === "ar" ? "rtl" : "ltr";
